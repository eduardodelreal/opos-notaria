const PREFIJOS: Record<BlockId, string> = {
  civil: 'CIVIL',
  mercantil: 'MERC',
  hipotecario: 'HIPO',
  notarial: 'NOT',
  fiscal: 'FISC',
  admin_procesal: 'ADM',
}

function build(bloque: BlockId, titulos: string[]): Tema[] {
  return titulos.map((titulo, i) => ({
    id: `${PREFIJOS[bloque]}_${String(i + 1).padStart(3, '0')}`,
    bloque,
    numero: i + 1,
    titulo,
  }))
}

